def resolve_path(path: Path) -> Path:
    """Resolve configured paths relative to this script."""
    return path if path.is_absolute() else (Path(__file__).resolve().parent / path).resolve()


def as_int_column(series: pd.Series, column_name: str) -> pd.Series:
    numeric = pd.to_numeric(series, errors="coerce")
    if numeric.isna().any():
        raise ValueError(f"Column {column_name!r} contains missing/non-numeric values.")
    rounded = np.rint(numeric.to_numpy(dtype=float))
    if not np.allclose(numeric.to_numpy(dtype=float), rounded):
        raise ValueError(f"Column {column_name!r} must contain integer values.")
    return pd.Series(rounded.astype(np.int64), index=series.index, name=column_name)


def load_dataset(csv_path: Path) -> pd.DataFrame:
    if not csv_path.is_file():
        raise FileNotFoundError(f"Dataset CSV not found: {csv_path}")

    df = pd.read_csv(csv_path)
    missing = [col for col in REQUIRED_CSV_COLUMNS if col not in df.columns]
    if missing:
        raise ValueError(f"Dataset is missing required columns: {missing}")

    for col in WORKLOAD_COLUMNS + TUNABLE_PARAMETERS:
        df[col] = as_int_column(df[col], col)

    if "THREAD_Z" in df.columns:
        df["THREAD_Z"] = as_int_column(df["THREAD_Z"], "THREAD_Z")
        thread_z_values = sorted(df["THREAD_Z"].dropna().unique().tolist())
        expected_thread_z = FIXED_PARAMETERS["THREAD_Z"]
        if thread_z_values and thread_z_values != [expected_thread_z]:
            raise ValueError(
                "The supplied PSO reference fixes THREAD_Z=1, but the CSV contains "
                f"THREAD_Z values {thread_z_values}. Update FIXED_PARAMETERS and the "
                "search/model setup consistently before evaluating."
            )
    else:
        df["THREAD_Z"] = FIXED_PARAMETERS["THREAD_Z"]

    df["latency_ms"] = pd.to_numeric(df["latency_ms"], errors="coerce")
    if df["latency_ms"].isna().any():
        raise ValueError("Column 'latency_ms' contains missing/non-numeric values.")

    if len(df) != EXPECTED_DATASET_ROWS:
        warnings.warn(
            f"Expected {EXPECTED_DATASET_ROWS} rows, found {len(df)}. Continuing.",
            RuntimeWarning,
        )

    return df


def validate_search_space() -> None:
    if set(SEARCH_SPACE) != set(TUNABLE_PARAMETERS):
        raise ValueError("SEARCH_SPACE keys and TUNABLE_PARAMETERS do not match.")
    for name, values in SEARCH_SPACE.items():
        if len(values) < 2:
            raise ValueError(f"SEARCH_SPACE[{name!r}] must contain at least two values.")
        if len(set(values)) != len(values):
            raise ValueError(f"SEARCH_SPACE[{name!r}] contains duplicate values.")
        if any(int(v) != v for v in values):
            raise ValueError(f"SEARCH_SPACE[{name!r}] must contain integers.")


def get_best_seen_by_workload(df: pd.DataFrame) -> dict[tuple[int, int, int, int], dict[str, Any]]:
    """Find the minimum positive measured latency for each (BATCH_SIZE, M, N, K)."""
    valid = df[np.isfinite(df["latency_ms"]) & (df["latency_ms"] > 0)].copy()
    if valid.empty:
        raise ValueError("The dataset contains no valid configurations (latency_ms > 0).")

    best_rows = valid.loc[valid.groupby(WORKLOAD_COLUMNS)["latency_ms"].idxmin()]
    result: dict[tuple[int, int, int, int], dict[str, Any]] = {}

    for _, row in best_rows.iterrows():
        shape = (int(row["BATCH_SIZE"]), int(row["M"]), int(row["N"]), int(row["K"]))
        config = {name: int(row[name]) for name in TUNABLE_PARAMETERS}
        config["THREAD_Z"] = int(row["THREAD_Z"])
        result[shape] = {
            "best_seen_latency_ms": float(row["latency_ms"]),
            "best_seen_config": config,
        }

    return result


def load_baseline_times(csv_path: Path) -> dict[tuple[int, int, int, int], float]:
    """Load measured baseline latencies produced by measure_bmm_baseline.py."""
    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Baseline results CSV not found: {csv_path}\n"
            "Run measure_bmm_baseline.py first, or update BASELINE_RESULTS_CSV."
        )

    baseline_df = pd.read_csv(csv_path)
    required = {"BATCH_SIZE", "M", "N", "K", "latency_ms"}
    missing_columns = sorted(required - set(baseline_df.columns))
    if missing_columns:
        raise ValueError(
            f"Baseline CSV is missing columns {missing_columns}. "
            f"Found columns: {list(baseline_df.columns)}"
        )

    # The baseline measurement script writes a status column. Only successful
    # measurements are accepted; failed/invalid baseline rows cannot be used
    # for speedup calculations.
    if "status" in baseline_df.columns:
        successful = baseline_df["status"].astype(str).str.lower().eq("success")
        failed_rows = baseline_df.loc[~successful, ["BATCH_SIZE", "M", "N", "K", "status"]]
        if not failed_rows.empty:
            warnings.warn(
                "Ignoring unsuccessful baseline measurements:\n"
                + failed_rows.to_string(index=False),
                RuntimeWarning,
            )
        baseline_df = baseline_df.loc[successful].copy()

    for column in ("BATCH_SIZE", "M", "N", "K"):
        numeric = pd.to_numeric(baseline_df[column], errors="coerce")
        if numeric.isna().any():
            raise ValueError(f"Baseline CSV column {column!r} has missing/non-numeric values.")
        rounded = np.rint(numeric.to_numpy(dtype=float))
        if not np.allclose(numeric.to_numpy(dtype=float), rounded):
            raise ValueError(f"Baseline CSV column {column!r} must contain integer values.")
        baseline_df[column] = rounded.astype(np.int64)

    baseline_df["latency_ms"] = pd.to_numeric(baseline_df["latency_ms"], errors="coerce")
    valid_latency = np.isfinite(baseline_df["latency_ms"]) & (baseline_df["latency_ms"] > 0)
    baseline_df = baseline_df.loc[valid_latency].copy()

    duplicate_mask = baseline_df.duplicated(subset=WORKLOAD_COLUMNS, keep=False)
    if duplicate_mask.any():
        duplicates = baseline_df.loc[duplicate_mask, WORKLOAD_COLUMNS + ["latency_ms"]]
        raise ValueError(
            "Baseline CSV must contain at most one successful row per (BATCH_SIZE, M, N, K). "
            "Duplicate workloads found:\n" + duplicates.to_string(index=False)
        )

    baseline_times = {
        (int(row.BATCH_SIZE), int(row.M), int(row.N), int(row.K)): float(row.latency_ms)
        for row in baseline_df[WORKLOAD_COLUMNS + ["latency_ms"]].itertuples(index=False)
    }
    if not baseline_times:
        raise ValueError(f"Baseline CSV contains no successful positive latencies: {csv_path}")

    return baseline_times


def validate_baselines(
    workloads: list[tuple[int, int, int, int]],
    baseline_times: dict[tuple[int, int, int, int], float],
) -> None:
    missing = [shape for shape in workloads if shape not in baseline_times]
    invalid = [
        shape for shape in workloads
        if shape in baseline_times
        and (not np.isfinite(baseline_times[shape]) or baseline_times[shape] <= 0)
    ]
    if missing or invalid:
        lines = [
            "Every workload must have a successful, positive baseline latency in BASELINE_RESULTS_CSV.",
            f"Missing workloads: {missing}",
        ]
        if invalid:
            lines.append(f"Non-positive/non-finite baseline values: {invalid}")
        raise ValueError("\n".join(lines))


def get_model_feature_columns(model: xgb.XGBRegressor) -> list[str]:
    if MODEL_FEATURE_COLUMNS is not None:
        return list(MODEL_FEATURE_COLUMNS)

    booster = model.get_booster()
    names = booster.feature_names
    available = set(RAW_FEATURE_COLUMNS + [
        "TOTAL_THREADS",
        "GRID_SIZE",
        "WORK_PER_THREAD_M",
        "WORK_PER_THREAD_N",
        "SHMEM_FOOTPRINT",
        "UNROLL_ALIGNMENT",
        "BOUNDARY_ALIGNMENT_M",
        "BOUNDARY_ALIGNMENT_N",
    ])

    # Prefer the actual named feature order saved in the model.
    if names and all(name in available for name in names):
        return list(names)

    # If the Booster has generic names (f0, f1, ...) or no names, infer only
    # the two feature layouts known from this project's BMM pipeline.
    n_features = int(booster.num_features())
    if n_features == len(RAW_FEATURE_COLUMNS):
        return list(RAW_FEATURE_COLUMNS)
    if n_features == len(RAW_FEATURE_COLUMNS) + 8:
        return list(RAW_FEATURE_COLUMNS) + [
            "TOTAL_THREADS",
            "GRID_SIZE",
            "WORK_PER_THREAD_M",
            "WORK_PER_THREAD_N",
            "SHMEM_FOOTPRINT",
            "UNROLL_ALIGNMENT",
            "BOUNDARY_ALIGNMENT_M",
            "BOUNDARY_ALIGNMENT_N",
        ]

    raise ValueError(
        f"Could not infer the model's {n_features} input features. Set "
        "MODEL_FEATURE_COLUMNS to the exact ordered feature list used during training."
    )


def build_feature_frame(
    configs: list[dict[str, int]],
    shape: tuple[int, int, int, int],
    model_feature_columns: list[str],
) -> pd.DataFrame:
    """Create raw + derived BMM features in the model's exact feature order."""
    rows = []
    for config in configs:
        rows.append({
            "BATCH_SIZE": shape[0],
            "M": shape[1],
            "N": shape[2],
            "K": shape[3],
            "TILE_M": int(config["TILE_M"]),
            "TILE_N": int(config["TILE_N"]),
            "TILE_K": int(config["TILE_K"]),
            "THREAD_X": int(config["THREAD_X"]),
            "THREAD_Y": int(config["THREAD_Y"]),
            "THREAD_Z": int(config["THREAD_Z"]),
            "UNROLL_FACTOR": int(config["UNROLL_FACTOR"]),
        })

    features = pd.DataFrame(rows, columns=RAW_FEATURE_COLUMNS)
    features["TOTAL_THREADS"] = (
        features["THREAD_X"] * features["THREAD_Y"] * features["THREAD_Z"]
    )
    features["GRID_SIZE"] = (
        np.ceil(features["M"] / features["TILE_M"])
        * np.ceil(features["N"] / features["TILE_N"])
        * features["BATCH_SIZE"]
    )
    features["WORK_PER_THREAD_M"] = (
        (features["TILE_M"] + features["THREAD_Y"] - 1) // features["THREAD_Y"]
    )
    features["WORK_PER_THREAD_N"] = (
        (features["TILE_N"] + features["THREAD_X"] - 1) // features["THREAD_X"]
    )
    features["SHMEM_FOOTPRINT"] = (
        features["TILE_M"] * features["TILE_K"]
        + features["TILE_K"] * features["TILE_N"]
    )
    features["UNROLL_ALIGNMENT"] = (
        (features["TILE_K"] % features["UNROLL_FACTOR"]) == 0
    ).astype(int)
    features["BOUNDARY_ALIGNMENT_M"] = (
        (features["M"] % features["TILE_M"]) == 0
    ).astype(int)
    features["BOUNDARY_ALIGNMENT_N"] = (
        (features["N"] % features["TILE_N"]) == 0
    ).astype(int)

    missing = [col for col in model_feature_columns if col not in features.columns]
    if missing:
        raise ValueError(f"Model expects features that this script cannot construct: {missing}")

    return features.loc[:, model_feature_columns]


