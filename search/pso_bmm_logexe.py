def parse_json_output(stdout: str) -> dict[str, Any]:
    text = stdout.strip()
    try:
        value = json.loads(text)
        if isinstance(value, dict):
            return value
    except json.JSONDecodeError:
        pass

    # Be tolerant of harmless text before/after the JSON object.
    first = text.find("{")
    last = text.rfind("}")
    if first >= 0 and last > first:
        value = json.loads(text[first:last + 1])
        if isinstance(value, dict):
            return value
    raise json.JSONDecodeError("No JSON object found in CUDA program output", text, 0)


def benchmark_final_config(
    shape: tuple[int, int, int, int],
    config: dict[str, int],
    cuda_source: Path,
) -> dict[str, Any]:
    """Compile/run one final config. This function is called after PSO timing."""
    if not cuda_source.is_file():
        return {
            "benchmark_status": "cuda_source_missing",
            "actual_latency_ms": np.nan,
            "benchmark_error": f"CUDA source not found: {cuda_source}",
        }

    compile_parameters = {
        "TILE_M": config["TILE_M"],
        "TILE_N": config["TILE_N"],
        "TILE_K": config["TILE_K"],
        "THREAD_X": config["THREAD_X"],
        "THREAD_Y": config["THREAD_Y"],
        "THREAD_Z": config["THREAD_Z"],
        "UNROLL_FACTOR": config["UNROLL_FACTOR"],
    }

    try:
        with tempfile.TemporaryDirectory(prefix="pso_bmm_compile_") as temp_dir:
            executable = Path(temp_dir) / "bmm_pso_eval"
            compile_cmd = [
                NVCC,
                "-O3",
                str(cuda_source),
                f"-arch={CUDA_ARCH}",
                "-o",
                str(executable),
            ]
            compile_cmd.extend(
                f"-D{name}={int(value)}" for name, value in compile_parameters.items()
            )

            try:
                compile_result = subprocess.run(
                    compile_cmd,
                    check=False,
                    capture_output=True,
                    text=True,
                    timeout=COMPILE_TIMEOUT_SECONDS,
                )
            except subprocess.TimeoutExpired:
                return {
                    "benchmark_status": "compile_timeout",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": f"nvcc exceeded {COMPILE_TIMEOUT_SECONDS}s",
                }

            if compile_result.returncode != 0:
                return {
                    "benchmark_status": "compilation_failed",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": (compile_result.stderr or compile_result.stdout)[-3000:],
                }

            batch, m, n, k = shape
            run_cmd = [str(executable), str(m), str(n), str(k), str(batch)]
            try:
                run_result = subprocess.run(
                    run_cmd,
                    check=False,
                    capture_output=True,
                    text=True,
                    timeout=EXECUTION_TIMEOUT_SECONDS,
                    cwd=str(cuda_source.parent),
                )
            except subprocess.TimeoutExpired:
                return {
                    "benchmark_status": "execution_timeout",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": f"CUDA executable exceeded {EXECUTION_TIMEOUT_SECONDS}s",
                }

            try:
                output = parse_json_output(run_result.stdout)
            except json.JSONDecodeError as exc:
                return {
                    "benchmark_status": "invalid_output",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": (
                        f"Could not parse CUDA JSON output: {exc}; "
                        f"stdout={run_result.stdout[-1500:]!r}; "
                        f"stderr={run_result.stderr[-1500:]!r}"
                    ),
                }

            status = str(output.get("status", "unknown_status"))
            if run_result.returncode != 0 and status == "success":
                return {
                    "benchmark_status": "execution_failed",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": run_result.stderr[-3000:],
                }

            if status != "success":
                return {
                    "benchmark_status": status,
                    "actual_latency_ms": np.nan,
                    "benchmark_error": str(output.get("error_message", "")),
                }

            latency = float(output.get("median_ms", np.nan))
            if not np.isfinite(latency) or latency <= 0:
                return {
                    "benchmark_status": "invalid_latency_value",
                    "actual_latency_ms": np.nan,
                    "benchmark_error": f"CUDA program returned median_ms={latency!r}",
                }

            return {
                "benchmark_status": "success",
                "actual_latency_ms": latency,
                "benchmark_error": "",
            }

    except FileNotFoundError as exc:
        return {
            "benchmark_status": "nvcc_or_executable_not_found",
            "actual_latency_ms": np.nan,
            "benchmark_error": str(exc),
        }
    except Exception as exc:
        return {
            "benchmark_status": "benchmark_exception",
            "actual_latency_ms": np.nan,
            "benchmark_error": repr(exc),
        }


def config_cache_key(
    shape: tuple[int, int, int, int], config: dict[str, int]
) -> tuple[int, ...]:
    return shape + tuple(int(config[name]) for name in TUNABLE_PARAMETERS) + (
        int(config["THREAD_Z"]),
    )


