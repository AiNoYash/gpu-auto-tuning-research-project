#!/usr/bin/env python3
"""Evaluate LocalBestPSO + an XGBoost LogExe surrogate for BMM.

The script:
1. Loads a measured BMM CSV containing (BATCH_SIZE, M, N, K), kernel parameters and latency_ms.
2. Uses the fastest valid measured configuration per workload as the best-seen reference.
3. Runs LocalBestPSO 25 times per workload for each requested swarm size.
4. Measures tuning wall time, including all XGBoost predict() calls made during PSO.
5. Benchmarks each distinct PSO-returned configuration with the supplied CUDA source.
   These final CUDA measurements are deliberately excluded from tuning time.
6. Writes per-run results and workload/swarm-size summaries.

Edit the paths below before running. The baseline latencies are loaded from BASELINE_RESULTS_CSV.
"""

