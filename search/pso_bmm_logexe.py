def add_run_metrics(
    run_df: pd.DataFrame,
    best_seen: dict[tuple[int, int, int, int], dict[str, Any]],
    baseline_times: dict[tuple[int, int, int, int], float],
) -> pd.DataFrame:
    out = run_df.copy()
    out["baseline_ms"] = np.nan
    out["best_seen_latency_ms"] = np.nan
    out["best_seen_config_json"] = ""
    out["speedup_vs_baseline"] = np.nan
    out["speedup_vs_best_seen"] = np.nan
    out["optimal_gap_pct"] = np.nan
    out["is_final_valid"] = False
    out["is_final_invalid"] = False
    out["is_benchmark_error"] = False

    for idx, row in out.iterrows():
        shape = (int(row["BATCH_SIZE"]), int(row["M"]), int(row["N"]), int(row["K"]))
        baseline = float(baseline_times[shape])
        best_info = best_seen[shape]
        best_latency = float(best_info["best_seen_latency_ms"])

        out.at[idx, "baseline_ms"] = baseline
        out.at[idx, "best_seen_latency_ms"] = best_latency
        out.at[idx, "best_seen_config_json"] = json.dumps(best_info["best_seen_config"])

        actual = row.get("actual_latency_ms", np.nan)
        is_valid = (
            row.get("benchmark_status") == "success"
            and pd.notna(actual)
            and np.isfinite(float(actual))
            and float(actual) > 0
        )
        benchmark_status = str(row.get("benchmark_status", ""))
        is_invalid_config = benchmark_status in INVALID_CONFIG_STATUSES
        is_benchmark_error = (
            benchmark_status not in {"success", "pso_failed", "not_run"}
            and not is_invalid_config
        )
        out.at[idx, "is_final_valid"] = bool(is_valid)
        out.at[idx, "is_final_invalid"] = bool(is_invalid_config)
        out.at[idx, "is_benchmark_error"] = bool(is_benchmark_error)

        if is_valid:
            actual = float(actual)
            out.at[idx, "speedup_vs_baseline"] = baseline / actual
            # This is the best-seen/best-returned latency ratio. It is 1.0
            # when PSO matches the reference; it can exceed 1.0 if PSO finds
            # a configuration faster than anything in the input CSV.
            out.at[idx, "speedup_vs_best_seen"] = best_latency / actual
            out.at[idx, "optimal_gap_pct"] = (
                (actual - best_latency) / best_latency * 100.0
            )

    for threshold in (1, 5, 10):
        out[f"near_optimal_{threshold}pct"] = (
            out["is_final_valid"] & (out["optimal_gap_pct"] <= threshold)
        ).astype(int)

    return out


def safe_mean(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").dropna()
    return float(values.mean()) if len(values) else np.nan


def safe_median(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").dropna()
    return float(values.median()) if len(values) else np.nan


def make_summary(run_df: pd.DataFrame) -> pd.DataFrame:
    summary_rows: list[dict[str, Any]] = []

    for (batch, m, n, k, n_particles), group in run_df.groupby(
        ["BATCH_SIZE", "M", "N", "K", "n_particles"], sort=True
    ):
        total_runs = len(group)
        has_config = group["pso_status"].eq("success")
        final_valid = group["is_final_valid"].astype(bool)
        invalid_final = group["is_final_invalid"].astype(bool)
        benchmark_errors = group["is_benchmark_error"].astype(bool)
        pso_errors = ~has_config

        row: dict[str, Any] = {
            "BATCH_SIZE": int(batch),
            "M": int(m),
            "N": int(n),
            "K": int(k),
            "n_particles": int(n_particles),
            "total_runs": int(total_runs),
            "valid_final_count": int(final_valid.sum()),
            "invalid_final_count": int(invalid_final.sum()),
            "invalid_final_rate_pct": (
                float(invalid_final.sum() / has_config.sum() * 100.0)
                if has_config.sum() else np.nan
            ),
            "benchmark_error_count": int(benchmark_errors.sum()),
            "pso_error_count": int(pso_errors.sum()),
            "best_seen_latency_ms": safe_mean(group["best_seen_latency_ms"]),
            "baseline_ms": safe_mean(group["baseline_ms"]),
            "mean_actual_latency_ms": safe_mean(group.loc[final_valid, "actual_latency_ms"]),
            "median_actual_latency_ms": safe_median(group.loc[final_valid, "actual_latency_ms"]),
            "mean_speedup_vs_baseline": safe_mean(group["speedup_vs_baseline"]),
            "median_speedup_vs_baseline": safe_median(group["speedup_vs_baseline"]),
            "mean_speedup_vs_best_seen": safe_mean(group["speedup_vs_best_seen"]),
            "median_speedup_vs_best_seen": safe_median(group["speedup_vs_best_seen"]),
            "mean_optimal_gap_pct": safe_mean(group["optimal_gap_pct"]),
            "median_optimal_gap_pct": safe_median(group["optimal_gap_pct"]),
            "mean_tuning_time_s": safe_mean(group["tuning_time_s"]),
            "median_tuning_time_s": safe_median(group["tuning_time_s"]),
            "mean_xgb_inference_time_s": safe_mean(group["xgb_inference_time_s"]),
            "median_xgb_inference_time_s": safe_median(group["xgb_inference_time_s"]),
            "mean_non_inference_overhead_s": safe_mean(group["non_inference_overhead_s"]),
            "median_non_inference_overhead_s": safe_median(group["non_inference_overhead_s"]),
        }

        for threshold in (1, 5, 10):
            # Denominator is all 25 attempts; invalid outputs and PSO errors fail.
            row[f"near_optimal_{threshold}pct_success_rate_pct"] = (
                float(group[f"near_optimal_{threshold}pct"].sum() / total_runs * 100.0)
                if total_runs else np.nan
            )

        summary_rows.append(row)

    return pd.DataFrame(summary_rows)


def main() -> None:
    validate_search_space()

    dataset_path = resolve_path(DATASET_CSV)
    model_path = resolve_path(MODEL_PATH)
    cuda_source = resolve_path(CUDA_SOURCE)
    baseline_csv_path = resolve_path(BASELINE_RESULTS_CSV)
    output_dir = resolve_path(OUTPUT_DIR)
    if RUN_GPU_BENCHMARK:
        if not cuda_source.is_file():
            raise FileNotFoundError(f"CUDA source not found: {cuda_source}")
        if which(NVCC) is None:
            raise FileNotFoundError(f"CUDA compiler not found: {NVCC}. Add it to PATH.")
    output_dir.mkdir(parents=True, exist_ok=True)

    df = load_dataset(dataset_path)
    workloads = sorted(
        (int(batch), int(m), int(n), int(k))
        for batch, m, n, k in df[WORKLOAD_COLUMNS].drop_duplicates().itertuples(index=False, name=None)
    )

    if len(workloads) != EXPECTED_WORKLOADS:
        raise ValueError(
            f"Expected {EXPECTED_WORKLOADS} unique (BATCH_SIZE, M, N, K) workloads, found {len(workloads)}: {workloads}"
        )

    baseline_times = load_baseline_times(baseline_csv_path)
    validate_baselines(workloads, baseline_times)

    best_seen = get_best_seen_by_workload(df)
    missing_best = [shape for shape in workloads if shape not in best_seen]
    if missing_best:
        raise ValueError(f"No valid (latency_ms > 0) reference configuration for: {missing_best}")

    for parameter, values in SEARCH_SPACE.items():
        data_values = set(df[parameter].astype(int).unique())
        search_values = set(int(v) for v in values)
        if not search_values.issubset(data_values):
            warnings.warn(
                f"SEARCH_SPACE[{parameter}] contains values not present in the CSV: "
                f"{sorted(search_values - data_values)}. This is allowed, but verify the domain.",
                RuntimeWarning,
            )

    if not model_path.is_file():
        raise FileNotFoundError(f"XGBoost model not found: {model_path}")
    model = xgb.XGBRegressor()
    model.load_model(str(model_path))
    model_feature_columns = get_model_feature_columns(model)

    print("=" * 78)
    print("BMM PSO + XGBoost evaluation")
    print(f"Dataset rows: {len(df)} | Workloads: {len(workloads)}")
    print(f"Baseline measurements: {baseline_csv_path}")
    print(f"Model features ({len(model_feature_columns)}): {model_feature_columns}")
    print(f"Particle counts: {PARTICLE_COUNTS} | Runs/workload/size: {N_RUNS} | Iterations: {N_ITERS}")
    print("GPU benchmarking is performed after PSO and is excluded from tuning time.")
    print("=" * 78)

    run_rows: list[dict[str, Any]] = []
    total_optimizations = len(workloads) * len(PARTICLE_COUNTS) * N_RUNS
    completed = 0

    for workload_index, shape in enumerate(workloads):
        best_info = best_seen[shape]
        print(
            f"\nWorkload {workload_index + 1}/{len(workloads)}: {shape} | "
            f"best-seen={best_info['best_seen_latency_ms']:.6f} ms | "
            f"baseline={baseline_times[shape]:.6f} ms"
        )

        for n_particles in PARTICLE_COUNTS:
            for run_number in range(1, N_RUNS + 1):
                result = run_single_pso(
                    model=model,
                    shape=shape,
                    model_feature_columns=model_feature_columns,
                    n_particles=n_particles,
                    run_number=run_number,
                    workload_index=workload_index,
                )
                completed += 1

                row: dict[str, Any] = {
                    "BATCH_SIZE": shape[0],
                    "M": shape[1],
                    "N": shape[2],
                    "K": shape[3],
                    "n_particles": n_particles,
                    "run": run_number,
                    "pso_iterations": N_ITERS,
                    "seed": result["seed"],
                    "pso_status": result["pso_status"],
                    "pso_error": result["pso_error"],
                    "best_predicted_log_latency": result["best_predicted_log_latency"],
                    "tuning_time_s": result["tuning_time_s"],
                    "xgb_inference_time_s": result["xgb_inference_time_s"],
                    "non_inference_overhead_s": result["non_inference_overhead_s"],
                }
                config = result["config"]
                for name in TUNABLE_PARAMETERS + ["THREAD_Z"]:
                    row[name] = config[name] if config is not None else np.nan
                run_rows.append(row)

                if completed % 10 == 0 or completed == total_optimizations:
                    print(
                        f"  PSO runs: {completed}/{total_optimizations} "
                        f"({100.0 * completed / total_optimizations:.1f}%)",
                        flush=True,
                    )

    run_df = pd.DataFrame(run_rows)

    # Benchmark each distinct final configuration once. This phase is outside
    # the recorded tuning_time_s, because it is post-selection verification.
    run_df["benchmark_status"] = "pso_failed"
    run_df["actual_latency_ms"] = np.nan
    run_df["benchmark_error"] = ""
    run_df["benchmark_cache_hit"] = False

    benchmark_cache: dict[tuple[int, ...], dict[str, Any]] = {}
    configs_to_benchmark = run_df[run_df["pso_status"] == "success"]

    if RUN_GPU_BENCHMARK:
        print(
            f"\nPSO complete. Benchmarking {len(configs_to_benchmark)} returned runs "
            "(deduplicating identical workload/configuration pairs)..."
        )

        for row_index, row in configs_to_benchmark.iterrows():
            shape = (int(row["BATCH_SIZE"]), int(row["M"]), int(row["N"]), int(row["K"]))
            config = {name: int(row[name]) for name in TUNABLE_PARAMETERS + ["THREAD_Z"]}
            key = config_cache_key(shape, config)

            if key in benchmark_cache:
                benchmark_result = benchmark_cache[key]
                run_df.at[row_index, "benchmark_cache_hit"] = True
            else:
                benchmark_result = benchmark_final_config(shape, config, cuda_source)
                benchmark_cache[key] = benchmark_result

            for name, value in benchmark_result.items():
                run_df.at[row_index, name] = value

            if len(benchmark_cache) % 10 == 0:
                print(
                    f"  Distinct final configurations benchmarked: {len(benchmark_cache)}",
                    flush=True,
                )
    else:
        run_df["benchmark_status"] = "not_run"
        run_df["benchmark_error"] = "RUN_GPU_BENCHMARK is False"

    run_df = add_run_metrics(run_df, best_seen, baseline_times)
    summary_df = make_summary(run_df)

    # Store the best-seen reference configuration per workload as part of the
    # summary so the source of the reference latency is explicit.
    best_config_json = {
        shape: json.dumps(info["best_seen_config"])
        for shape, info in best_seen.items()
    }
    summary_df["best_seen_config_json"] = summary_df.apply(
        lambda r: best_config_json[(int(r["BATCH_SIZE"]), int(r["M"]), int(r["N"]), int(r["K"]))],
        axis=1,
    )

    details_path = output_dir / "pso_bmm_run_details.csv"
    summary_path = output_dir / "pso_bmm_summary.csv"
    report_path = output_dir / "pso_bmm_report.txt"
    run_df.to_csv(details_path, index=False)
    summary_df.to_csv(summary_path, index=False)

    report_header = [
        "BMM LogExe PSO evaluation",
        f"Workloads: {len(workloads)} | Reference rows: {len(df)} | PSO runs: {len(run_df)}",
        f"Particles: {PARTICLE_COUNTS} | Runs per workload and size: {N_RUNS} | Iterations: {N_ITERS}",
        f"Reference dataset: {dataset_path}",
        f"Default latency CSV: {baseline_csv_path}",
        f"LogExe model: {model_path}",
        f"Distinct final configurations benchmarked: {len(benchmark_cache)}",
        "Best seen is the minimum valid measured latency in the reference CSV for each workload.",
        "A negative gap means PSO beat that reference. Near-optimal rates count all attempts.",
        "Invalid-output rates use runs that returned a configuration.",
        "CUDA median latency is measured after PSO and reused for identical workload/configuration pairs.",
        "Tuning time excludes final CUDA benchmarking.",
        "",
    ]
    report_columns = summary_df.columns.drop(
        [*WORKLOAD_COLUMNS, "n_particles", "best_seen_config_json"]
    )
    with report_path.open("w", encoding="utf-8") as report:
        report.write("\n".join(report_header) + "\n")
        for row in summary_df.to_dict("records"):
            report.write(f"\nWorkload ({row['BATCH_SIZE']}, {row['M']}, {row['N']}, {row['K']}) | {row['n_particles']} particles\n")
            for column in report_columns:
                value = row[column]
                display = "n/a" if pd.isna(value) else f"{value:.6g}"
                report.write(f"  {column}: {display}\n")
            report.write(f"  best_seen_config_json: {row['best_seen_config_json']}\n")
        report.write(f"\nPer-run metrics and selected configurations: {details_path.name}\n")

    print("\n" + "=" * 78)
    print("SUMMARY")
    display_columns = [
        "BATCH_SIZE", "M", "N", "K", "n_particles",
        "near_optimal_1pct_success_rate_pct",
        "near_optimal_5pct_success_rate_pct",
        "near_optimal_10pct_success_rate_pct",
        "mean_speedup_vs_baseline",
        "mean_speedup_vs_best_seen",
        "mean_optimal_gap_pct",
        "mean_tuning_time_s",
        "mean_xgb_inference_time_s",
        "invalid_final_count",
    ]
    print(summary_df[display_columns].to_string(index=False))
    print("\nSaved:")
    print(f"  Run details: {details_path}")
    print(f"  Summary:     {summary_path}")
    print(f"  Text report: {report_path}")
    print(f"Distinct final configurations benchmarked: {len(benchmark_cache)}")
    print("=" * 78)


if __name__ == "__main__":
    main()
