class XGBoostFitness:
    """Batch objective for PySwarms; accumulates only model.predict() time."""

    def __init__(
        self,
        model: xgb.XGBRegressor,
        shape: tuple[int, int, int, int],
        model_feature_columns: list[str],
    ) -> None:
        self.model = model
        self.shape = shape
        self.model_feature_columns = model_feature_columns
        self.inference_time_s = 0.0

    def positions_to_configs(self, swarm_positions: np.ndarray) -> list[dict[str, int]]:
        indices = np.rint(swarm_positions).astype(np.int64)
        configs: list[dict[str, int]] = []

        for particle_indices in indices:
            config = {}
            for dim, parameter in enumerate(TUNABLE_PARAMETERS):
                domain = SEARCH_SPACE[parameter]
                index = int(np.clip(particle_indices[dim], 0, len(domain) - 1))
                config[parameter] = int(domain[index])
            config.update(FIXED_PARAMETERS)
            configs.append(config)

        return configs

    def __call__(self, swarm_positions: np.ndarray) -> np.ndarray:
        configs = self.positions_to_configs(swarm_positions)
        model_input = build_feature_frame(
            configs, self.shape, self.model_feature_columns
        )

        start = time.perf_counter()
        predictions = self.model.predict(model_input)
        self.inference_time_s += time.perf_counter() - start

        predictions = np.asarray(predictions, dtype=float).reshape(-1)
        # Keep a failed/non-finite model output from crashing PSO.
        return np.nan_to_num(
            predictions,
            nan=1.0e12,
            posinf=1.0e12,
            neginf=1.0e12,
        )


def decode_position(position: np.ndarray) -> dict[str, int]:
    indices = np.rint(position).astype(np.int64)
    config: dict[str, int] = {}
    for dim, parameter in enumerate(TUNABLE_PARAMETERS):
        domain = SEARCH_SPACE[parameter]
        index = int(np.clip(indices[dim], 0, len(domain) - 1))
        config[parameter] = int(domain[index])
    config.update(FIXED_PARAMETERS)
    return config


def run_single_pso(
    model: xgb.XGBRegressor,
    shape: tuple[int, int, int, int],
    model_feature_columns: list[str],
    n_particles: int,
    run_number: int,
    workload_index: int,
) -> dict[str, Any]:
    seed = BASE_RANDOM_SEED + workload_index * 100_000 + n_particles * 100 + run_number
    np.random.seed(seed)

    objective = XGBoostFitness(model, shape, model_feature_columns)
    options = {
        "c1": PSO_C1,
        "c2": PSO_C2,
        "w": PSO_W,
        "k": min(PSO_K, n_particles),
        "p": PSO_P,
    }

    lower_bounds = np.zeros(len(TUNABLE_PARAMETERS), dtype=float)
    upper_bounds = np.array(
        [len(SEARCH_SPACE[name]) - 1 for name in TUNABLE_PARAMETERS],
        dtype=float,
    )
    bounds = (lower_bounds, upper_bounds)

    start = time.perf_counter()
    try:
        optimizer = ps.single.LocalBestPSO(
            n_particles=n_particles,
            dimensions=len(TUNABLE_PARAMETERS),
            options=options,
            bounds=bounds,
            bh_strategy="nearest",
            ftol=-np.inf,
        )
        best_cost, best_position = optimizer.optimize(
            objective,
            iters=N_ITERS,
            verbose=False,
        )
        tuning_time_s = time.perf_counter() - start

        return {
            "pso_status": "success",
            "pso_error": "",
            "seed": seed,
            "best_predicted_log_latency": float(best_cost),
            "config": decode_position(best_position),
            "tuning_time_s": float(tuning_time_s),
            "xgb_inference_time_s": float(objective.inference_time_s),
            "non_inference_overhead_s": float(
                max(0.0, tuning_time_s - objective.inference_time_s)
            ),
        }
    except Exception as exc:  # keep the other independent runs going
        tuning_time_s = time.perf_counter() - start
        return {
            "pso_status": "pso_error",
            "pso_error": repr(exc),
            "seed": seed,
            "best_predicted_log_latency": np.nan,
            "config": None,
            "tuning_time_s": float(tuning_time_s),
            "xgb_inference_time_s": float(objective.inference_time_s),
            "non_inference_overhead_s": float(
                max(0.0, tuning_time_s - objective.inference_time_s)
            ),
        }


